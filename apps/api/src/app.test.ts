test("a versioned route without an authorization policy cannot be registered", async () => {
  const app = await buildApp();
  assert.throws(() => app.get("/v1/unsafe", async () => ({})), /ROUTE_AUTHORIZATION_POLICY_REQUIRED/);
  assert.throws(() => app.get("/v1/metadata-only", {
    config: { permission: "handoff.read" },
  }, async () => ({})), /ROUTE_AUTHORIZATION_POLICY_REQUIRED/);
  assert.throws(() => app.get("/v1/forged", {
    config: { permission: "handoff.read", authorizationEnforced: true },
  }, async () => ({})), /ROUTE_AUTHORIZATION_POLICY_REQUIRED/);
  assert.throws(() => app.get("/v1/ambiguous", {
    config: { public: true, permission: "handoff.read" },
  }, async () => ({})), /ROUTE_AUTHORIZATION_POLICY_AMBIGUOUS/);
  await app.close();
});

