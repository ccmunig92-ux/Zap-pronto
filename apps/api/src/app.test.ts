test("a unit-scoped route fails closed when its resolver does not return a UUID", async () => {
  const database = authorizationPool();
  const app = await buildApp({ identityVerifier: {
    async verifyBearer() {
      return { issuer: "https://issuer.example", audience: "zap-pronto", subject: "subject-1" };
    },
  } });
  let handlerCalled = false;
  app.get("/v1/unit-probe", protectedRoute({
    pool: database.pool,
    permission: "handoff.read",
    scope: {
      kind: "unit",
      async resolveUnitId() { return undefined as unknown as string; },
    },
    async handler() { handlerCalled = true; return {}; },
  }));
  const response = await app.inject({
    method: "GET", url: "/v1/unit-probe", headers: { authorization: "Bearer accepted" },
  });
  assert.equal(response.statusCode, 403);
  assert.equal(handlerCalled, false);
  assert.ok(database.queries.includes("ROLLBACK"));
  assert.ok(!database.queries.some((query) => query.includes("current_actor_has_permission")));
  await app.close();
});
